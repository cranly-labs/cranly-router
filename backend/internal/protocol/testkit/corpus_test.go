package testkit

import (
	"os"
	"path/filepath"
	"testing"
	"testing/fstest"

	"github.com/stretchr/testify/require"

	"github.com/TokenFlux/TokenRouter/internal/protocol"
)

// TestCorpusIndexingAndQueries builds an in-memory testdata filesystem covering
// wire fixtures, recorded client requests, recorded upstream SSE streams, and
// ignored _incoming files. It verifies protocol alias resolution, tag filtering,
// SSE frame decoding, DefaultCorpus embedding, and Go source scanning.
func TestCorpusIndexingAndQueries(t *testing.T) {
	rawReadme, err := ReadTestdataFile("README.md")
	require.NoError(t, err)
	require.Contains(t, string(rawReadme), "Protocol testkit data layout")

	mapFS := fstest.MapFS{
		"wire/messages/request/tool_single.json": &fstest.MapFile{
			Data: []byte(`{"model":"claude-sonnet-4-5","max_tokens":64,"messages":[{"role":"user","content":"hi"}]}`),
		},
		"wire/openai_chat_completions/stream/text_basic.sse": &fstest.MapFile{
			Data: []byte("data: {\"id\":\"1\",\"object\":\"chat.completion.chunk\",\"created\":1,\"model\":\"gpt-4o\",\"choices\":[{\"index\":0,\"delta\":{\"role\":\"assistant\",\"content\":\"hi\"},\"finish_reason\":\"stop\"}]}\n\ndata: [DONE]\n\n"),
		},
		"corpus/clients/codex/0.169.0/lab_tool/meta.json": &fstest.MapFile{
			Data: []byte(`{"protocol":"openai_responses","client":"codex","version":"0.169.0","scenario":"lab_tool","tags":["tools","cli"]}`),
		},
		"corpus/clients/codex/0.169.0/lab_tool/1.request.json": &fstest.MapFile{
			Data: []byte(`{"model":"gpt-5","input":"run ls"}`),
		},
		"corpus/upstreams/anthropic/claude-sonnet-4-5/lab_text/meta.json": &fstest.MapFile{
			Data: []byte(`{"protocol":"messages","provider":"anthropic","model":"claude-sonnet-4-5","stream":true,"tags":["smoke"]}`),
		},
		"corpus/upstreams/anthropic/claude-sonnet-4-5/lab_text/1.stream.sse": &fstest.MapFile{
			Data: []byte("event: message_start\ndata: {\"type\":\"message_start\"}\n\n"),
		},
		"corpus/_incoming/unredacted.request.json": &fstest.MapFile{
			Data: []byte(`{"secret":"sk-ant-should-be-ignored"}`),
		},
	}

	c := NewCorpus(mapFS)

	wireReqs, err := c.QueryFixtures(FixtureQuery{
		Protocol: protocol.ProtocolAnthropicMessages,
		Kind:     FixtureRequest,
		Source:   SourceWire,
	})
	require.NoError(t, err)
	require.Len(t, wireReqs, 1)
	require.Equal(t, "tool_single", wireReqs[0].Scenario)

	clientReqs, err := c.QueryFixtures(FixtureQuery{
		Protocol: protocol.ProtocolOpenAIResponses,
		Source:   SourceCorpusClient,
		Client:   "codex",
		Tags:     []string{"tools", "cli"},
	})
	require.NoError(t, err)
	require.Len(t, clientReqs, 1)
	require.Equal(t, "codex/0.169.0/lab_tool/1", clientReqs[0].Name)

	streams, err := c.QueryFixtures(FixtureQuery{
		Protocol: protocol.ProtocolOpenAIChatCompletions,
		Kind:     FixtureStream,
	})
	require.NoError(t, err)
	require.Len(t, streams, 1)
	frames, err := streams[0].Frames()
	require.NoError(t, err)
	require.Len(t, frames, 2)

	// Verify ReadGoProductionSources skips _test.go and generated files.
	srcDir := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(srcDir, "prod.go"), []byte("package sample\nfunc X() {}\n"), 0o644))
	require.NoError(t, os.WriteFile(filepath.Join(srcDir, "prod_test.go"), []byte("package sample\n"), 0o644))
	require.NoError(t, os.WriteFile(filepath.Join(srcDir, "gen.go"), []byte("// Code generated by tool. DO NOT EDIT.\npackage sample\n"), 0o644))
	sources, err := ReadGoProductionSources(srcDir)
	require.NoError(t, err)
	require.Len(t, sources, 1)
	require.Contains(t, sources[0].Path, "prod.go")
}
